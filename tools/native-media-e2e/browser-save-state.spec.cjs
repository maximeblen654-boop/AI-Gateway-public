const { test, expect } = require('../../frontend/node_modules/@playwright/test')
for (const width of [1440, 1366, 390]) test(`candidate confirmed save and independent video calculator ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: width === 1366 ? 650 : 844 })
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/tests/media-workbench/index.html?scenario=DRAFT_MANAGEMENT_VIDEO_LIMITS&theme=blue&mode=light')
  const w = id => page.locator(`[data-test="${id}"]`)
  await w('account-search').fill('#77'); await w('supplier-77').click(); await w('model-video-model').click()
  await w('wizard-step-4').click()
  await expect(w('video-sale-editor')).toBeVisible()
  await page.locator('input[data-test^="video-sale-"]').first().fill('2.34')
  const status = w('autosave-status').locator(':scope > p').first()
  await expect(status).toHaveText('已确认保存')
  const saved = await page.evaluate(() => ({ snapshot: window.mediaFixture.snapshot(), calls: window.mediaFixture.calls.filter(x => x.method !== 'get') }))
  const last = saved.calls.at(-1), config = saved.snapshot.media_workbench_v1
  // Vue fixture models one save increment, not Core's separate validation CAS.
  // This proves UI/receipt behavior only; browser.cjs validates real Core +2.
  expect(config.record_version).toBe(last.input.expected_record_version + 1)
  expect(config.draft.save_receipt).toEqual({ submission_id: last.input.submission_id, base_record_version: last.input.expected_record_version, draft_revision: config.draft.revision })
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const trigger = await w('independent-calculator-open').boundingBox()
  expect(Math.abs(trigger.x + trigger.width - width)).toBeLessThanOrEqual(2)
  await w('independent-calculator-open').click()
  const drawer = await page.getByRole('dialog', { name: '成本计算器', exact: true }).boundingBox()
  expect(Math.abs(drawer.x + drawer.width - width)).toBeLessThanOrEqual(2)
  expect(drawer.y).toBeLessThanOrEqual(2)
  await w('independent-purchase').fill('100'); await w('independent-credits').fill('1000'); await w('independent-consumption').fill('15')
  await expect(w('independent-result')).toHaveText('1.5 元')
  await page.screenshot({ path: info.outputPath('confirmed-save-calculator.png'), fullPage: false })
  await page.keyboard.press('Escape')
  await expect(w('independent-calculator-open')).toBeFocused()
  await expect(status).toHaveText('已确认保存')
  expect(await page.evaluate(() => window.mediaFixture.calls.filter(x => x.method !== 'get'))).toEqual(saved.calls)
  expect(await page.evaluate(() => window.mediaFixture.snapshot())).toEqual(saved.snapshot)
})
