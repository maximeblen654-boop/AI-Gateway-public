import { test, expect, type Page } from '@playwright/test'
const snapshot = (page: Page) => page.evaluate(() => window.procurementFixture.snapshot())
const writes = (page: Page) => page.evaluate(() => window.procurementFixture.calls.filter(c => c.method !== 'get'))
async function openVideo(page: Page, scenario = 'video-retail') {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto(`/tests/workbench-procurement/index.html?scenario=${scenario}`)
  await page.getByTestId('account-search').fill('#44')
  await page.getByTestId('supplier-44').click()
  await page.getByTestId('model-WAN3.0-可参考视频').click()
  await page.getByTestId('wizard-step-4').click()
}
for (const viewport of [{ width: 1440, height: 900 }, { width: 1366, height: 650 }, { width: 390, height: 844 }]) {
  test(`video retail groups and independent right calculator ${viewport.width}`, async ({ page }, info) => {
    await page.setViewportSize(viewport)
    await openVideo(page)
    await expect(page.getByTestId('video-sale-editor')).toBeVisible()
    await expect(page.locator('input[data-test^="video-sale-"]')).toHaveCount(12)
    await expect(page.getByTestId('procurement-cost-0')).toHaveCount(0)
    await page.getByTestId('video-sale-4').fill('2')
    await page.getByTestId('video-sale-5').fill('4')
    await page.getByTestId('arithmetic-preview').click()
    await expect(page.getByRole('dialog')).toContainText('每下一档增加 2 元')
    await page.getByTestId('arithmetic-confirm').click()
    await expect(page.getByTestId('video-sale-6')).toHaveValue('6')
    await expect(page.getByTestId('video-sale-15')).toHaveValue('24')
    await page.getByTestId('sale-resolution-4K').click()
    await expect(page.locator('input[data-test^="video-sale-"]')).toHaveCount(12)
    await expect(page.getByTestId('video-sale-4')).toHaveValue('')
    await page.getByTestId('video-sale-4').fill('9')
    await page.getByTestId('sale-resolution-720p').click()
    await expect(page.getByTestId('video-sale-4')).toHaveValue('2')
    await expect(page.getByTestId('autosave-status')).toContainText('已确认保存')
    const before = await snapshot(page), calls = await writes(page)
    const trigger = page.getByTestId('independent-calculator-open')
    const rect = await trigger.boundingBox()
    expect(rect).not.toBeNull()
    expect(rect!.x + rect!.width).toBeCloseTo(viewport.width, 0)
    await trigger.click()
    const dialog = page.getByRole('dialog')
    const drawer = await dialog.boundingBox()
    expect(drawer!.x + drawer!.width).toBeCloseTo(viewport.width, 0)
    expect(drawer!.y).toBe(0)
    await page.getByTestId('independent-purchase').fill('100')
    await page.getByTestId('independent-credits').fill('10000')
    await page.getByTestId('independent-consumption').fill('35')
    await expect(page.getByTestId('independent-result')).toContainText('0.35 元')
    await expect(page.getByTestId('independent-profit')).toHaveText('—')
    await expect(page.getByTestId('independent-margin')).toHaveText('—')
    await page.getByTestId('independent-sale').fill('1')
    await expect(page.getByTestId('independent-profit')).toHaveText('0.65 元')
    await expect(page.getByTestId('independent-margin')).toHaveText('65%')
    await page.screenshot({ path: info.outputPath(`calculator-right-${viewport.width}.png`), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await expect(page.getByTestId('independent-consumption')).toHaveValue('35')
    await expect(page.getByTestId('independent-sale')).toHaveValue('1')
    await page.getByRole('button', { name: '关闭成本与利润计算器', exact: true }).click()
    expect(await snapshot(page)).toEqual(before)
    expect(await writes(page)).toEqual(calls)
    await page.getByTestId('video-sale-editor').scrollIntoViewIfNeeded()
    await page.screenshot({ path: info.outputPath(`video-sale-${viewport.width}.png`), animations: 'disabled' })
    await page.reload()
    await page.getByTestId('account-search').fill('#44'); await page.getByTestId('supplier-44').click()
    await page.getByTestId('model-WAN3.0-可参考视频').click(); await page.getByTestId('wizard-step-4').click()
    await expect(page.getByTestId('video-sale-4')).toHaveValue('2')
    await page.getByTestId('sale-resolution-4K').click()
    await expect(page.getByTestId('video-sale-4')).toHaveValue('9')
    expect((await writes(page)).filter(c => !c.url.endsWith('/draft'))).toHaveLength(0)
  })
}
test('editing a shared video price preserves the other resolution and duration', async ({ page }) => {
  await openVideo(page, 'video-retail-shared')
  await expect(page.getByTestId('video-sale-4')).toHaveValue('3')
  await page.getByTestId('video-sale-4').fill('7')
  await expect(page.getByTestId('video-sale-5')).toHaveValue('3')
  await page.getByTestId('sale-resolution-4K').click()
  await expect(page.getByTestId('video-sale-4')).toHaveValue('3')
  await expect(page.getByTestId('video-sale-15')).toHaveValue('3')
})

test('video sale autosave serializes newer prices without procurement or publication writes', async ({ page }) => {
  await openVideo(page, 'recovery-video-serialized')
  await page.evaluate(() => window.procurementFixture.failNext('draft', 'delay'))
  await page.getByTestId('video-sale-5').fill('4')
  await expect.poll(async () => (await writes(page)).length).toBe(1)
  await page.getByTestId('video-sale-5').fill('4.5')
  await page.getByTestId('video-sale-10').fill('8')
  expect((await writes(page)).length).toBe(1)
  await page.evaluate(() => window.procurementFixture.release())
  await expect(page.getByTestId('autosave-status')).toContainText('已确认保存')
  const product = (await snapshot(page)).media_workbench_v1!.draft.products.find(p => p.product_id === 'procurement-wan')!
  expect(product.pricing_rules.find(r => r.match.duration_seconds?.includes(5))?.sale_price?.amount).toBe('4.5')
  expect(product.pricing_rules.find(r => r.match.duration_seconds?.includes(10))?.sale_price?.amount).toBe('8')
  await expect(page.getByTestId('video-sale-5')).toHaveValue('4.5')
  expect((await writes(page)).every(c => c.method === 'put' && c.url.endsWith('/draft'))).toBe(true)
  await expect(page.getByTestId('procurement-cost-0')).toHaveCount(0)
})