const fixture = (page: Page) => page.evaluate(() => (window as unknown as { procurementFixture: Fixture }).procurementFixture.snapshot())
const puts = (page: Page) => page.evaluate(() => (window as unknown as { procurementFixture: Fixture }).procurementFixture.calls.filter(c => c.method === 'put' && c.url.endsWith('/draft')).length)
const image = async (page: Page) => (await fixture(page)).media_workbench_v1.draft.products.find(p => p.product_id === 'procurement-image')!

