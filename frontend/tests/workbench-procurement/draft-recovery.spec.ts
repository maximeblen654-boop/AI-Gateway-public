test('serialized save retains newer edits while an older response is delayed', async ({ page }) => {
  await open(page, 'serialized')
  await page.evaluate(() => (window as unknown as { procurementFixture: Fixture }).procurementFixture.failNext('draft', 'delay'))
  await page.getByTestId('price-0').fill('0.31')
  await expect.poll(() => puts(page)).toBe(1)
  await expect(page.getByTestId('price-1')).toBeEnabled()
  await page.getByTestId('price-1').fill('1.23')
  await page.getByTestId('price-2').fill('0.62')
  expect(await puts(page)).toBe(1)
  await page.evaluate(() => (window as unknown as { procurementFixture: Fixture }).procurementFixture.release())
  await expect.poll(async () => (await image(page)).pricing_rules[1]?.sale_price?.amount).toBe('1.23')
  await expect.poll(async () => (await image(page)).pricing_rules[2]?.sale_price?.amount).toBe('0.62')
  await expect(page.getByTestId('price-0')).toHaveValue('0.31')
  await expect(page.getByTestId('price-1')).toHaveValue('1.23')
  expect(await puts(page)).toBeLessThanOrEqual(3)
})

