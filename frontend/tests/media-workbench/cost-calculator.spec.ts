import { test, expect, type Page } from '@playwright/test'
import type { Product, SupplierDetail } from '../../src/api/admin/mediaWorkbench'

type Call = { method: string; url: string; input: { submission_id: string; expected_record_version: number; draft: { products: Product[] } } }
const snapshot = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { snapshot: () => SupplierDetail } }).mediaFixture.snapshot())
const writes = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { calls: Call[] } }).mediaFixture.calls.filter(call => call.method !== 'get'))

for (const width of [1440, 390]) for (const mode of ['light', 'dark']) {
  test(`cost estimate ${width} ${mode}: local estimate, explicit adoption, confirmed autosave and reload`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    await page.goto(`/tests/media-workbench/index.html?scenario=WIZARD&mode=${mode}&theme=blue`)
    await page.getByTestId('account-search').fill('#77'); await page.getByTestId('supplier-77').click(); await page.getByTestId('model-image-native-1').click()
    await page.getByTestId('wizard-step-4').click()
    await expect(page.getByTestId('inline-cost-calculator')).toBeVisible()
    await page.getByTestId('price-0').fill('0.70')
    await expect(page.getByTestId('autosave-status')).toContainText('已确认保存')
    const beforeEstimate = await snapshot(page), beforeWrites = await writes(page)
    await page.getByTestId('cost-purchase').fill('100')
    await page.getByTestId('cost-credits').fill('1000')
    await page.getByTestId('cost-consumption-0').fill('8')
    await expect(page.getByTestId('cost-rate')).toContainText('0.1 CNY')
    await expect(page.getByTestId('converted-cost-0')).toContainText('0.8 CNY')
    await expect(page.getByTestId('procurement-cost-0')).toHaveValue('')
    // Estimation remains local even when leaving the step flushes pending product edits.
    await page.getByTestId('wizard-step-3').click(); await page.getByTestId('wizard-step-4').click()
    expect(await snapshot(page)).toEqual(beforeEstimate)
    expect(await writes(page)).toEqual(beforeWrites)
    await expect(page.getByTestId('cost-consumption-0')).toHaveValue('8')
    const pricesBefore = await page.locator('input[data-spec-price]').evaluateAll(inputs => inputs.map(input => (input as HTMLInputElement).value))
    await page.getByTestId('cost-apply-0').click()
    await expect(page.getByTestId('procurement-cost-0')).toHaveValue('0.8')
    expect(await page.locator('input[data-spec-price]').evaluateAll(inputs => inputs.map(input => (input as HTMLInputElement).value))).toEqual(pricesBefore)
    await expect.poll(async () => (await snapshot(page)).media_workbench_v1!.draft.products[0]!.cost_rules?.[0]?.cost?.amount).toBe('0.8')
    await expect(page.getByTestId('autosave-status')).toContainText('已确认保存')
    await expect(page.getByTestId('draft-recovery')).toHaveCount(0)
    for (const input of await page.locator('input[data-spec-cost]').all()) await expect(input).toHaveValue('0.8')
    const saved = (await snapshot(page)).media_workbench_v1!, requests = await writes(page)
    expect(requests.length).toBeGreaterThan(beforeWrites.length)
    requests.forEach((call, index) => {
      expect(call.method).toBe('put'); expect(call.url).toBe('/admin/media-workbench/accounts/77/draft')
      expect(call.input.expected_record_version).toBe(3 + index)
    })
    const last = requests[requests.length - 1]!.input
    expect(saved.draft.save_receipt).toEqual({ submission_id: last.submission_id, base_record_version: last.expected_record_version, draft_revision: saved.draft.revision })
    expect(saved.draft.products).toEqual(last.draft.products)
    expect(saved.published).toEqual(beforeEstimate.media_workbench_v1!.published)
    expect(saved.sales).toEqual(beforeEstimate.media_workbench_v1!.sales)
    expect(saved.draft.products[0]!.pricing_rules[0]!.sale_price!.amount).toBe('0.70')
    await page.getByTestId('spec-row-0').scrollIntoViewIfNeeded()
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath(`calculator-${width}-${mode}.png`), fullPage: false, animations: 'disabled' })
    await page.getByTestId('inline-cost-calculator').screenshot({ path: info.outputPath(`calculator-detail-${width}-${mode}.png`), animations: 'disabled' })
    await info.attach('confirmed-cost-contract', { body: JSON.stringify({ requests, saved }, null, 2), contentType: 'application/json' })
    await page.reload()
    await page.getByTestId('account-search').fill('#77'); await page.getByTestId('supplier-77').click(); await page.getByTestId('model-image-native-1').click()
    await page.getByTestId('wizard-step-4').click()
    await expect(page.getByTestId('procurement-cost-0')).toHaveValue('0.8')
    await expect(page.getByTestId('price-0')).toHaveValue('0.70')
    await expect(page.getByTestId('cost-purchase')).toHaveValue('100')
    await expect(page.getByTestId('cost-consumption-0')).toHaveValue('8')
    await page.getByTestId('cost-consumption-0').fill('0')
    await expect(page.getByTestId('converted-cost-0')).toContainText('0 CNY')
    await expect(page.getByTestId('procurement-cost-0')).toHaveValue('0.8')
    expect((await snapshot(page)).media_workbench_v1!.draft.products[0]!.cost_rules![0]!.cost!.amount).toBe('0.8')
  })
}
