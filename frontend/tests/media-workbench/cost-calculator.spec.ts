import { test, expect, type Page } from '@playwright/test'
import type { Product, SupplierDetail } from '../../src/api/admin/mediaWorkbench'

type Call = { method: string; url: string; input: { submission_id: string; expected_record_version: number; draft: { products: Product[] } } }
const snapshot = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { snapshot: () => SupplierDetail } }).mediaFixture.snapshot())
const writes = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { calls: Call[] } }).mediaFixture.calls.filter(call => call.method !== 'get'))

for (const width of [1440, 390]) for (const mode of ['light', 'dark']) {
  test(`independent profit estimate ${width} ${mode}: no product adoption; confirmed retail save and reload`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    await page.goto(`/tests/media-workbench/index.html?scenario=WIZARD&mode=${mode}&theme=blue`)
    await page.getByTestId('account-search').fill('#77'); await page.getByTestId('supplier-77').click(); await page.getByTestId('model-image-native-1').click()
    await page.getByTestId('wizard-step-4').click()
    await expect(page.getByTestId('inline-cost-calculator')).toHaveCount(0)
    await expect(page.getByTestId('procurement-cost-0')).toHaveCount(0)
    await page.getByTestId('price-0').fill('0.70')
    await expect(page.getByTestId('autosave-status')).toContainText('已确认保存')
    const beforeEstimate = await snapshot(page), beforeWrites = await writes(page)
    const saved = beforeEstimate.media_workbench_v1!, last = beforeWrites.at(-1)!.input
    expect(saved.draft.save_receipt).toEqual({ submission_id: last.submission_id, base_record_version: last.expected_record_version, draft_revision: saved.draft.revision })
    expect(saved.draft.products).toEqual(last.draft.products)
    beforeWrites.forEach((call, index) => {
      expect(call.method).toBe('put'); expect(call.url).toBe('/admin/media-workbench/accounts/77/draft')
      expect(call.input.expected_record_version).toBe(3 + index)
      expect(call.input.draft.products.every(product => !('cost_rules' in product) && !('cost_version' in product))).toBe(true)
    })
    expect(new Set(beforeWrites.map(call => call.input.submission_id)).size).toBe(beforeWrites.length)
    await page.getByTestId('independent-calculator-open').click()
    const drawer = page.getByRole('dialog', { name: '成本与利润计算器', exact: true })
    await page.getByTestId('independent-purchase').fill('100')
    await page.getByTestId('independent-credits').fill('1000')
    await page.getByTestId('independent-consumption').fill('8')
    await page.getByTestId('independent-sale').fill('1')
    await expect(page.getByTestId('independent-unit')).toHaveText('0.1 元')
    await expect(page.getByTestId('independent-result')).toHaveText('0.8 元')
    await expect(page.getByTestId('independent-profit')).toHaveText('0.2 元')
    await expect(page.getByTestId('independent-margin')).toHaveText('20%')
    await expect(page.getByTestId('cost-apply-0')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath(`calculator-${width}-${mode}.png`), animations: 'disabled' })
    await drawer.screenshot({ path: info.outputPath(`calculator-detail-${width}-${mode}.png`), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('independent-calculator-open')).toBeFocused()
    await page.getByTestId('wizard-step-3').click(); await page.getByTestId('wizard-step-4').click()
    expect(await snapshot(page)).toEqual(beforeEstimate)
    expect(await writes(page)).toEqual(beforeWrites)
    await expect(page.getByTestId('price-0')).toHaveValue('0.70')
    await expect(page.getByTestId('draft-recovery')).toHaveCount(0)
    await info.attach('retail-save-and-local-calculator-boundary', { body: JSON.stringify({ requests: beforeWrites, saved }, null, 2), contentType: 'application/json' })
    await page.reload()
    await page.getByTestId('account-search').fill('#77'); await page.getByTestId('supplier-77').click(); await page.getByTestId('model-image-native-1').click()
    await page.getByTestId('wizard-step-4').click()
    await expect(page.getByTestId('price-0')).toHaveValue('0.70')
    await expect(page.getByTestId('procurement-cost-0')).toHaveCount(0)
    const beforeZero = await snapshot(page), zeroWrites = await writes(page)
    await page.getByTestId('independent-calculator-open').click()
    await expect(page.getByTestId('independent-purchase')).toHaveValue('100')
    await expect(page.getByTestId('independent-consumption')).toHaveValue('8')
    await page.getByTestId('independent-consumption').fill('0')
    await expect(page.getByTestId('independent-result')).toHaveText('0 元')
    await expect(page.getByTestId('independent-profit')).toHaveText('1 元')
    await page.keyboard.press('Escape')
    expect(await snapshot(page)).toEqual(beforeZero)
    expect(await writes(page)).toEqual(zeroWrites)
  })
}
