import { test, expect, type Page } from '@playwright/test'

async function openGroups(page: Page, query = '') {
  await page.goto(`/tests/media-workbench/index.html?${query}`)
  await expect(page.getByTestId('browse-by-source')).toHaveAttribute('aria-pressed', 'true')
  await page.getByTestId('browse-by-group').click()
  await expect(page.getByTestId('site-group-31')).toBeVisible()
}
test.beforeEach(async ({ page }) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
})
for (const width of [1440, 390]) {
  test(`group identity, navigation and retained context ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    await openGroups(page)
    await expect(page.getByText('上游来源', { exact: true })).toBeVisible()
    await expect(page.getByText('供应商账号', { exact: true })).toBeVisible()
    const group = page.getByTestId('site-group-31')
    await group.locator('summary').click()
    await expect(group.getByTestId('group-member-77')).toContainText('账号 #77')
    await expect(group.getByTestId('group-member-44')).toContainText('示例视频供应商')
    await expect(group.getByTestId('group-member-77')).toContainText('账号正常 · 可调度')
    await expect(page.locator('.app-layout-content')).toHaveCSS('margin-left', width >= 1024 ? '256px' : '0px')
    await page.getByTestId('account-page').screenshot({ path: info.outputPath(`group-members-${width}.png`) })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByTestId('group-open-account-77').click()
    await expect(page.getByTestId('model-page')).toBeVisible()
    await page.getByRole('button', { name: '← 返回来源与账号', exact: true }).click()
    await expect(page.getByTestId('browse-by-group')).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByTestId('site-group-31').getByTestId('group-member-77')).toBeVisible()
    await expect(page.getByTestId('group-open-account-77')).toBeFocused()
    await page.getByTestId('browse-by-source').click()
    await expect(page.getByTestId('account-search')).toBeVisible()
    await page.getByTestId('browse-by-group').click()
    await expect(page.getByTestId('site-group-31').getByTestId('group-member-77')).toBeVisible()
    const calls = await page.evaluate(() => (window as unknown as { mediaFixture: { calls: { method: string; url: string }[] } }).mediaFixture.calls)
    expect(calls.filter(call => call.method !== 'get')).toEqual([])
  })
}
test('empty, disabled, ungrouped, shared, non-media and paginated memberships', async ({ page }) => {
  await openGroups(page)
  const empty = page.getByTestId('site-group-32')
  await expect(empty).toContainText('分组已停用')
  await empty.locator('summary').click()
  await expect(empty.getByTestId('empty-members')).toContainText('尚未关联账号')
  const shared = page.getByTestId('site-group-33')
  await shared.locator('summary').click()
  await expect(shared.getByTestId('group-member-77')).toBeVisible()
  await expect(shared.getByTestId('group-member-99')).toContainText('已停止调度')
  await expect(shared.getByTestId('group-open-account-99')).toHaveCount(0)
  await page.getByTestId('site-group-ungrouped').locator('summary').click()
  await expect(page.getByTestId('group-member-88')).toBeVisible()
  const many = page.getByTestId('site-group-34')
  await many.locator('summary').click()
  await expect(many).toContainText('已显示 50 / 51 个账号')
  await many.getByTestId('more-members').click()
  await expect(many.getByTestId('group-member-151')).toBeVisible()
  await expect(many.getByTestId('more-members')).toHaveCount(0)
  await page.getByTestId('group-search').fill('#31')
  await expect(page.getByTestId('site-group-32')).toHaveCount(0)
  await expect(page.getByTestId('site-group-31')).toBeVisible()
})
test('read failures remain errors and retry without losing the selected group', async ({ page }) => {
  await openGroups(page, 'membersFailOnce=31')
  const group = page.getByTestId('site-group-31')
  await group.locator('summary').click()
  await expect(group.getByTestId('members-error')).toBeVisible()
  await expect(group.getByTestId('empty-members')).toHaveCount(0)
  await group.getByRole('button', { name: '重试读取成员', exact: true }).click()
  await expect(group.getByTestId('group-member-77')).toBeVisible()
})


test('second-page media account remains visible and focused after returning', async ({ page }) => {
  await openGroups(page, 'groupSecondPageMedia=1')
  const group = page.getByTestId('site-group-34')
  await group.locator('summary').click()
  await group.getByTestId('more-members').click()
  await expect(group.getByTestId('group-open-account-151')).toBeVisible()
  await group.getByTestId('group-open-account-151').click()
  await expect(page.getByTestId('model-page')).toBeVisible()
  await page.getByRole('button', { name: '← 返回来源与账号', exact: true }).click()
  await expect(group.getByTestId('group-open-account-151')).toBeVisible()
  await expect(group.getByTestId('group-open-account-151')).toBeFocused()
  await expect(group.getByTestId('more-members')).toHaveCount(0)
})
