import { test, expect } from '@playwright/test'
for (const width of [1440, 390]) {
  test(`video duration and reference limits ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 844 })
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    page.on('dialog', dialog => dialog.accept())
    await page.goto('/tests/media-workbench/index.html?scenario=DRAFT_MANAGEMENT_VIDEO_LIMITS&theme=blue&mode=light')
    await page.getByTestId('account-search').fill('#77')
    await page.getByTestId('supplier-77').click()
    await page.getByTestId('model-video-model').click()
    await page.getByTestId('duration-start').fill('4')
    await page.getByTestId('duration-end').fill('30')
    await page.getByTestId('duration-step').fill('1')
    await page.getByTestId('duration-add').click()
    const tokens = page.locator('.mw-field').filter({ has: page.getByTestId('duration-range') }).getByTestId('tokens-input')
    await expect(tokens).toHaveValue(Array.from({ length: 27 }, (_, i) => i + 4).join(', '))
    await page.getByRole('button', { name: '移除时长 17 秒', exact: true }).click()
    await expect(tokens).toHaveValue(Array.from({ length: 27 }, (_, i) => i + 4).filter(n => n !== 17).join(', '))
    await page.getByTestId('duration-range').scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath('duration-range-viewport.png'), animations: 'disabled' })
    await page.getByTestId('wizard-step-2').click()
    await page.getByTestId('reference-image-max').fill('30')
    await page.getByTestId('reference-total').fill('30')
    await expect(page.getByTestId('reference-image-max')).toHaveAttribute('max', '30')
    await expect(page.getByTestId('reference-error')).toHaveCount(0)
    await page.getByTestId('reference-video-mode').selectOption('optional')
    await page.getByTestId('reference-video-max').fill('2')
    await expect(page.getByTestId('reference-error')).toHaveCount(0)
    await page.getByTestId('reference-image-max').fill('31')
    await page.getByTestId('reference-image-max').press('Enter')
    await expect(page.getByTestId('reference-error')).toContainText('0～30')
    await page.getByTestId('reference-image-max').fill('30')
    await page.getByTestId('reference-image-max').press('Enter')
    await page.getByTestId('reference-editor').scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath('reference-limit-viewport.png'), animations: 'disabled' })
    const writes = await page.evaluate(() => (window as unknown as { mediaFixture: { calls: Array<{method:string;url:string;input:{draft:{products:Array<{capabilities:{references:{image:{max:number};total_max:number}}}>}}}> } }).mediaFixture.calls.filter(call => call.method !== 'get'))
    // Accepted edits may autosave. Invalid 31 must never reach a draft request;
    // neither publication nor sales/generation requests are allowed here.
    for (const call of writes) {
      expect(call.method).toBe('put'); expect(call.url).toMatch(/\/draft$/)
      expect(call.input.draft.products[0]!.capabilities.references.image.max).toBeLessThanOrEqual(30)
      expect(call.input.draft.products[0]!.capabilities.references.total_max).toBeLessThanOrEqual(30)
    }
  })
}
