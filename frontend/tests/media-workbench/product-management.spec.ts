import { test, expect, type Page } from '@playwright/test'

type Snapshot = { media_workbench_v1: { draft: { products: Array<{ product_id: string; enabled: boolean; [key: string]: unknown }> }; published: unknown; sales: unknown } }
const snapshot = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { snapshot: () => Snapshot } }).mediaFixture.snapshot())
const calls = (page: Page) => page.evaluate(() => (window as unknown as { mediaFixture: { calls: Array<{ method: string; url: string; input: { draft?: { products: unknown[]; remove_product_ids?: string[] } } }> } }).mediaFixture.calls)
async function editor(page: Page, kind: string) {
  await page.getByTestId('account-search').fill('#77')
  await page.getByTestId('supplier-77').click()
  await page.getByTestId(`model-${kind === 'IMAGE' ? 'gpt-image-2' : 'video-model'}`).click()
}
async function options(page: Page) {
  const panel = page.getByTestId('product-options')
  if (!await panel.getAttribute('open').then(value => value !== null)) await panel.locator('summary').click()
}
for (const kind of ['IMAGE', 'VIDEO']) for (const width of [1440, 390]) {
  test(`seven drafts ${kind} ${width}: explicit creation, undo and selected removal`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 1440 ? 1100 : 844 })
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
    await page.goto(`/tests/media-workbench/index.html?scenario=DRAFT_MANAGEMENT_${kind}&theme=blue&mode=${width === 390 ? 'dark' : 'light'}`)
    await editor(page, kind)
    const before = await snapshot(page)
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(7)
    await expect(page.getByTestId('product-enabled')).toBeVisible()
    await expect(page.getByRole('button', { name: /添加.*产品/ })).toHaveCount(0)
    await options(page)
    await expect(page.getByTestId('remove-blank-product')).toHaveCount(0)
    await expect(page.getByTestId('removal-protection')).toContainText('已发布')
    await page.screenshot({ path: info.outputPath('configured-product.png'), fullPage: true })
    await page.getByTestId('new-independent-product').click()
    await expect(page.getByRole('dialog', { name: '另建独立销售商品？' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(7)
    await page.getByTestId('new-independent-product').click()
    await page.screenshot({ path: info.outputPath('create-confirmation.png'), fullPage: true })
    await page.getByTestId('confirm-add-product').evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(8)
    await page.getByTestId('undo-add-product').click()
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(7)
    expect((await calls(page)).filter(call => call.method !== 'get')).toEqual([])
    expect(await snapshot(page)).toEqual(before)
    for (const id of ['blank-1', 'blank-6', 'canvas-1', 'blank-3']) await page.getByTestId('product-select').selectOption(id)
    await expect(page.getByTestId('product-status')).toContainText('已停用')
    await options(page)
    await page.screenshot({ path: info.outputPath('blank-management.png'), fullPage: true })
    await page.getByTestId('remove-blank-product').click()
    await page.screenshot({ path: info.outputPath('remove-confirmation.png'), fullPage: true })
    await page.getByTestId('confirm-remove-product').click()
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(6)
    await page.getByTestId('undo-removal-blank-3').click()
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(7)
    await options(page); await page.getByTestId('remove-blank-product').click(); await page.getByTestId('confirm-remove-product').click()
    await page.getByTestId('save-removals').click()
    await expect(page.getByTestId('pending-removals')).toHaveCount(0)
    const after = await snapshot(page)
    expect(after.media_workbench_v1.draft.products).toEqual(before.media_workbench_v1.draft.products.filter(p => p.product_id !== 'blank-3'))
    expect(after.media_workbench_v1.published).toEqual(before.media_workbench_v1.published)
    expect(after.media_workbench_v1.sales).toEqual(before.media_workbench_v1.sales)
    const writes = (await calls(page)).filter(call => call.method !== 'get')
    expect(writes).toHaveLength(1); expect(writes[0]!.url).toMatch(/\/draft$/)
    expect(writes[0]!.input.draft!.remove_product_ids).toEqual(['blank-3'])
    await page.reload(); await editor(page, kind)
    await expect(page.getByTestId('product-select').locator('option')).toHaveCount(6)
    expect((await snapshot(page)).media_workbench_v1.draft.products[0]).toEqual(before.media_workbench_v1.draft.products[0])
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: info.outputPath('saved-reread.png'), fullPage: true })
    await info.attach('product-identities-and-save', { body: JSON.stringify({ before, after, writes }, null, 2), contentType: 'application/json' })
  })
}
test('one configured product creates a second only after explicit confirmation and saves enable state separately', async ({ page }) => {
  await page.goto('/tests/media-workbench/index.html?scenario=DRAFT_MANAGEMENT_IMAGE_SINGLE')
  await editor(page, 'IMAGE')
  await expect(page.getByTestId('product-select')).toHaveCount(0)
  await options(page); await page.getByTestId('new-independent-product').click()
  expect((await snapshot(page)).media_workbench_v1.draft.products).toHaveLength(1)
  await page.getByTestId('confirm-add-product').click()
  await expect(page.getByTestId('product-select').locator('option')).toHaveCount(2)
  await page.getByTestId('product-enabled').uncheck()
  await page.getByTestId('wizard-step-5').click(); await page.getByTestId('save').click()
  await expect(page.getByTestId('undo-add-product')).toHaveCount(0)
  const saved = (await snapshot(page)).media_workbench_v1.draft.products
  expect(saved).toHaveLength(2); expect(saved[0]!.product_id).toBe('canvas-1'); expect(saved[1]!.enabled).toBe(false)
  expect((await calls(page)).filter(call => call.method !== 'get').map(call => call.url)).toEqual(['/admin/media-workbench/accounts/77/draft'])
})


test('changing generation and edit limits, saving and rereading keeps exactly seven identities and prices', async ({ page }, info) => {
  await page.goto('/tests/media-workbench/index.html?scenario=DRAFT_MANAGEMENT_IMAGE')
  await editor(page, 'IMAGE')
  const before = await snapshot(page)
  const identities = before.media_workbench_v1.draft.products.map(p => p.product_id)
  await page.getByTestId('advanced-technical').locator('summary').first().click()
  await page.getByTestId('image-execution-advanced').locator('summary').click()
  const records: unknown[] = []
  for (const prefix of ['image-execution', 'image-edit-execution']) for (const max of [10, 1, 2]) {
    await page.getByTestId(`${prefix}-mode`).selectOption(max === 1 ? 'single' : 'native_multi')
    if (max !== 1) await page.getByTestId(`${prefix}-max`).fill(String(max))
    await page.getByTestId('wizard-step-5').click(); await page.getByTestId('save').click()
    await expect(page.getByTestId('unsaved')).toHaveCount(0)
    const after = await snapshot(page)
    expect(after.media_workbench_v1.draft.products.map(p => p.product_id)).toEqual(identities)
    expect(after.media_workbench_v1.draft.products.map(p => p.pricing_rules)).toEqual(before.media_workbench_v1.draft.products.map(p => p.pricing_rules))
    expect(after.media_workbench_v1.draft.products.map(p => p.capabilities)).toEqual(before.media_workbench_v1.draft.products.map(p => p.capabilities))
    expect(after.media_workbench_v1.published).toEqual(before.media_workbench_v1.published)
    records.push({ prefix, max, ids: identities, selected: await page.getByTestId('product-select').inputValue(), writes: (await calls(page)).filter(call => call.method !== 'get') })
  }
  await page.reload(); await editor(page, 'IMAGE')
  await expect(page.getByTestId('product-select').locator('option')).toHaveCount(7)
  await info.attach('quantity-identity-records', { body: JSON.stringify(records, null, 2), contentType: 'application/json' })
})
