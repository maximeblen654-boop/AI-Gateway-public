import { test, expect, type Page } from '@playwright/test'

type Fixture = { calls: { method: string; url: string; input: unknown }[]; groups: () => { id: number; name: string }[]; setGroupDeleteOutcome: (outcome: 'reject' | 'hold') => void; releaseGroupDelete: () => void }
async function open(page: Page) {
  await page.goto('/tests/media-workbench/index.html')
  await page.getByTestId('browse-by-group').click()
  await expect(page.getByTestId('site-group-32')).toBeVisible()
}
async function writes(page: Page) { return page.evaluate(() => (window as unknown as { mediaFixture: Fixture }).mediaFixture.calls.filter(call => call.method !== 'get')) }
test.beforeEach(async ({ page }) => {
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
})
for (const width of [1440, 390]) {
  test(`native delete confirmation, failure and retry ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 1000 })
    await open(page)
    await page.getByTestId('site-group-32').locator('summary').click()
    await page.getByTestId('delete-site-group-32').click()
    const dialog = page.getByRole('dialog', { name: '删除分组', exact: true })
    await expect(dialog).toContainText('待接入的图片分组 (#32)')
    await expect(dialog).toContainText('账号本身保留')
    await expect(page.locator('aside')).toHaveCount(1)
    expect(await writes(page)).toEqual([])
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    expect(await writes(page)).toEqual([])
    await page.getByTestId('native-group-management').getByRole('button', { name: '删除', exact: true }).click()
    await page.evaluate(() => (window as unknown as { mediaFixture: Fixture }).mediaFixture.setGroupDeleteOutcome('reject'))
    await dialog.getByRole('button', { name: '删除', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('删除未完成')
    await expect(dialog).toBeVisible()
    await page.screenshot({ path: info.outputPath(`native-delete-error-${width}.png`) })
    await page.evaluate(() => (window as unknown as { mediaFixture: Fixture }).mediaFixture.setGroupDeleteOutcome('hold'))
    await dialog.getByRole('button', { name: '删除', exact: true }).click()
    await expect(dialog.getByRole('button', { name: '删除', exact: true })).toBeDisabled()
    await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
    await expect(page.getByTestId('back-to-group-members')).toBeDisabled()
    await page.evaluate(() => (window as unknown as { mediaFixture: Fixture }).mediaFixture.releaseGroupDelete())
    await expect(dialog).not.toBeVisible()
    await page.getByTestId('back-to-group-members').click()
    await expect(page.getByTestId('site-group-32')).toHaveCount(0)
    await expect(page.getByTestId('site-group-31')).toBeVisible()
    const mutations = await writes(page)
    expect(mutations.map(call => [call.method, call.url])).toEqual([['delete', '/admin/groups/32'], ['delete', '/admin/groups/32']])
  })
}
test('native create, edit and duplicate stay inside the media workbench', async ({ page }, info) => {
  await open(page)
  await page.getByTestId('create-site-group').click()
  const create = page.getByRole('dialog', { name: '创建分组', exact: true })
  await expect(create).toBeVisible()
  await create.locator('input[type="text"]').first().fill('新建创作分组')
  await create.getByRole('button', { name: '创建', exact: true }).click()
  await expect(create).not.toBeVisible()
  await page.getByTestId('back-to-group-members').click()
  const group = page.getByTestId('site-group-35')
  await expect(group).toContainText('新建创作分组')
  await group.locator('summary').click()
  await group.getByRole('button', { name: '编辑分组', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑分组', exact: true })
  await expect(edit).toBeVisible()
  await edit.locator('input[type="text"]').first().fill('已编辑的创作分组')
  await edit.getByRole('button', { name: '更新', exact: true }).click()
  await expect(edit).not.toBeVisible()
  await page.getByTestId('back-to-group-members').click()
  await expect(page.getByTestId('site-group-35')).toContainText('已编辑的创作分组')
  await page.getByTestId('manage-site-groups').click()
  const row = page.getByRole('row').filter({ hasText: '已编辑的创作分组' })
  await row.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '已编辑的创作分组 (Copy)' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('native-group-management.png') })
  await page.getByTestId('back-to-group-members').click()
  await expect(page.getByTestId('site-group-36')).toContainText('已编辑的创作分组 (Copy)')
  expect((await writes(page)).map(call => [call.method, call.url])).toEqual([['post', '/admin/groups'], ['put', '/admin/groups/35'], ['post', '/admin/groups/35/duplicate']])
  expect(page.url()).toContain('/tests/media-workbench/index.html')
})
