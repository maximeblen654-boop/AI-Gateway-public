import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) for (const mode of ['light', 'dark']) {
  test(`sales categories drill down without changing products at ${width} ${mode}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:4190/') && route.request().method() === 'GET' ? route.continue() : route.abort())
    await page.goto(`/tests/media-workbench/index.html?scenario=SALES_CATEGORIES&theme=blue&mode=${mode}`)
    await page.getByTestId('account-search').fill('#77')
    await page.getByTestId('supplier-77').click()
    const snapshot = () => page.evaluate(() => (window as unknown as { mediaFixture: { snapshot: () => unknown } }).mediaFixture.snapshot())
    const screenshot = async (name: string) => {
      await page.evaluate(async () => {
        await document.fonts.ready
        window.scrollTo(0, 0)
        await new Promise<void>(resolve => requestAnimationFrame(() => resolve()))
      })
      await page.screenshot({ path: info.outputPath(name), fullPage: true })
    }
    const before = await snapshot()
    const panel = page.getByTestId('product-readiness-list')
    await expect(panel.getByTestId('sales-categories').locator('button')).toHaveCount(5)
    await expect(panel.locator('[data-test^="readiness-"]')).toHaveCount(0)
    for (const [id, count] of [['ready', 2], ['unpublished', 1], ['unlisted', 2], ['attention', 1], ['archived', 1]] as const) {
      await expect(page.getByTestId(`sales-category-${id}`).locator('.mw-sales-count')).toHaveText(String(count))
    }
    await screenshot(`categories-${width}-${mode}.png`)
    await page.getByTestId('sales-category-ready').focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('sales-category-heading')).toBeFocused()
    await expect(panel.locator('[data-test^="readiness-"]')).toHaveCount(2)
    await expect(panel).toContainText('晴空图片')
    await expect(panel).toContainText('流光创作')
    await expect(panel).not.toContainText('旧款图片商品')
    await screenshot(`ready-${width}-${mode}.png`)
    await page.getByTestId('sales-categories-back').click()
    await expect(page.getByTestId('sales-category-ready')).toBeFocused()
    await page.getByTestId('sales-category-unpublished').click()
    await expect(panel.locator('[data-test^="readiness-"]')).toHaveCount(1)
    await expect(panel).toContainText('补齐规格和售价')
    await panel.getByRole('button', { name: '编辑此商品' }).click()
    await expect(page.getByTestId('editor-page')).toBeVisible()
    await expect(page.getByTestId('selected-model-summary')).toContainText('新建创作商品')
    await expect(page.getByTestId('selected-product-readiness')).toContainText('尚未发布')
    await page.getByRole('button', { name: '← 返回模型列表', exact: true }).click()
    await expect(page.getByTestId('sales-category-heading')).toContainText('尚未发布')
    await page.getByTestId('sales-categories-back').click()
    await page.getByTestId('sales-category-unlisted').click()
    await expect(panel.locator('[data-test^="readiness-"]')).toHaveCount(2)
    await expect(panel).toContainText('重新上架')
    await expect(panel).not.toContainText('晴空图片')
    await page.getByTestId('sales-categories-back').click()
    await page.getByTestId('sales-category-attention').click()
    await expect(panel).toContainText('待核对的上游商品')
    await expect(panel).toContainText('先同步上游目录')
    await expect(panel.getByRole('button', { name: '同步上游目录', exact: true })).toBeVisible()
    await page.getByTestId('view-catalog-report').click()
    await expect(page.getByTestId('catalog-copy')).toBeFocused()
    await expect(page.getByTestId('catalog-notice')).toContainText('复制检查与修复提示词')
    await page.getByTestId('sales-categories-back').click()
    await page.getByTestId('sales-category-archived').click()
    await expect(page.getByTestId('sales-category-heading')).toContainText('已收起')
    await expect(panel).toContainText('先恢复显示')
    expect(await snapshot()).toEqual(before)
    const writes = await page.evaluate(() => (window as unknown as { mediaFixture: { calls: Array<{ method: string }> } }).mediaFixture.calls.filter(call => call.method !== 'get'))
    expect(writes).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    expect(errors).toEqual([])
  })
}
