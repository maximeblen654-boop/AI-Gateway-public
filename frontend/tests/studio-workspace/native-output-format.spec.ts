import {test,expect} from '@playwright/test'
for(const viewport of [{width:1440,height:900},{width:1366,height:650},{width:390,height:844}])test(`native format choice and quotation ${viewport.width}x${viewport.height}`,async({page},info)=>{
 await page.setViewportSize(viewport)
 await page.goto('/tests/studio-workspace/index.html?scenario=native-format')
 await expect(page.getByTestId('studio-output-format')).toContainText('由模型决定')
 await page.getByTestId('studio-output-format').click()
 await expect(page.locator('#studio-output-format-menu [data-value]')).toHaveCount(4)
 await page.locator('#studio-output-format-menu [data-value="jpeg"]').click()
 await expect(page.getByTestId('studio-output-format')).toContainText('JPEG')
 const button=page.getByTestId('studio-quote')
 await expect(page.locator('#studio-output-format-menu')).toHaveCount(0)
 if(viewport.width<700)await button.scrollIntoViewIfNeeded()
 const box=await button.boundingBox();expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.y+box!.height).toBeLessThanOrEqual(viewport.height+1)
 await page.screenshot({path:info.outputPath(`native-format-${viewport.width}.png`)})
 await page.getByTestId('studio-prompt').fill('Non-paid isolated format quote')
 await button.click()
 await expect(page.getByRole('dialog')).toContainText('JPEG')
 const calls=await page.evaluate(()=>(window as any).studioFixture.calls as {method:string;path:string;body:any}[])
 expect(calls.find(call=>call.path.endsWith('/image/quotes'))?.body.spec.output_format).toBe('jpeg')
 expect(calls.filter(call=>call.method==='POST'&&call.path.endsWith('/tasks'))).toHaveLength(0)
})
