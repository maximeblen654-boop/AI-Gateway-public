import {test,expect} from '@playwright/test'

for(const viewport of [{width:1440,height:900},{width:1366,height:650},{width:390,height:844}])test(`published ratio picker ${viewport.width}x${viewport.height}`,async({page},info)=>{
 await page.setViewportSize(viewport)
 await page.goto('/tests/studio-workspace/index.html?scenario=published-ratios')
 const toggle=page.getByTestId('studio-ratio-toggle')
 await expect(toggle).toBeEnabled()
 await expect(page.locator('input[type=range]')).toHaveCount(0)
 await toggle.click()
 const menu=page.getByRole('group',{name:'选择画面比例'})
 await expect(menu.locator('button')).toHaveCount(4)
 await expect(menu.locator('input')).toHaveCount(0)
 await menu.locator('[data-ratio="7:5"]').focus()
 await page.keyboard.press('Enter')
 await expect(toggle).toContainText('7:5')
 const calls=await page.evaluate(()=>(window as any).studioFixture.calls as {method:string;path:string;body:any}[])
 expect(calls.filter(call=>call.method==='POST'&&(call.path.endsWith('/quotes')||call.path.endsWith('/tasks')))).toHaveLength(0)
 await toggle.scrollIntoViewIfNeeded()
 await page.screenshot({path:info.outputPath(`published-ratios-${viewport.width}.png`)})
 await page.getByTestId('studio-prompt').fill('Isolated published custom ratio quote')
 await page.getByTestId('studio-quote').click()
 await expect(page.getByRole('dialog')).toBeVisible()
 const quoted=await page.evaluate(()=>(window as any).studioFixture.calls.find((call:any)=>call.path.endsWith('/image/quotes')))
 expect(quoted.body.offer_id).toBe('ratio-2');expect(quoted.body.spec.aspect_ratio).toBe('7:5')
})

test('mobile published ratio picker supports touch selection without quoting',async({browser,baseURL})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true})
 const page=await context.newPage();await page.goto(`${baseURL}/tests/studio-workspace/index.html?scenario=published-ratios`)
 const toggle=page.getByTestId('studio-ratio-toggle');await toggle.scrollIntoViewIfNeeded();await toggle.tap()
 await page.locator('[data-ratio="16:9"]').tap();await expect(toggle).toContainText('16:9')
 expect(await page.evaluate(()=>(window as any).studioFixture.calls.filter((call:any)=>call.method==='POST'&&(call.path.endsWith('/quotes')||call.path.endsWith('/tasks'))))).toEqual([])
 await context.close()
})
