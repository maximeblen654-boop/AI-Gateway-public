import { test, expect } from '@playwright/test'

for (const viewport of [{width:1440,height:900},{width:1366,height:650},{width:390,height:844}]) test(`one product / exact specification Offer ${viewport.width}`, async ({page},info) => {
  await page.setViewportSize(viewport)
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/tests/studio-workspace/index.html?scenario=product-offers')
  await page.getByTestId('studio-model-toggle').click()
  await expect(page.locator('.picker-choice')).toHaveCount(1)
  await expect(page.locator('.picker-choice small')).toContainText('2K / 4K')
  await page.locator('.picker-choice').click()
  await page.getByTestId('studio-resolution').click()
  await page.locator('#studio-resolution-menu [data-value="4K"]').click()
  await page.getByTestId('studio-prompt').fill('Isolated image quote')
  await page.getByTestId('studio-quote').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  const image=await page.evaluate(()=>(window as any).studioFixture.calls.find((c:any)=>c.path.endsWith('/image/quotes')))
  expect(image.body.offer_id).toBe('image-4K');expect(image.body.spec.resolution).toBe('4K')
  await page.getByRole('button',{name:'返回修改'}).click()
  await page.getByTestId('studio-mode-video').click()
  await page.getByTestId('studio-model-toggle').click()
  await expect(page.locator('.picker-choice')).toHaveCount(1)
  await expect(page.locator('.picker-choice small')).toContainText('5 / 10 / 15 秒')
  await page.screenshot({path:info.outputPath(`grouped-video-${viewport.width}.png`),animations:'disabled'})
  await page.locator('.picker-choice').click()
  await page.getByTestId('studio-duration').click()
  await page.locator('#studio-duration-menu [data-value="15"]').click()
  await page.getByTestId('studio-prompt').fill('Isolated video quote')
  await page.getByTestId('studio-quote').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText('15 CNY')
  const calls=await page.evaluate(()=>(window as any).studioFixture.calls)
  const quote=calls.find((c:any)=>c.path.endsWith('/video/quotes'))
  expect(quote.body).toMatchObject({offer_id:'video-15',duration:15,resolution:'720p',ratio:'16:9'})
  expect(calls.filter((c:any)=>c.method==='POST'&&c.path.endsWith('/tasks'))).toHaveLength(0)
  await page.screenshot({path:info.outputPath(`exact-offer-quote-${viewport.width}.png`),animations:'disabled'})
})

for (const viewport of [{width:1440,height:900},{width:390,height:844}]) for(const mediaKind of ['image','video'] as const) test(`${mediaKind} reference count switches the exact Offer and price ${viewport.width}`,async({page},info)=>{
 await page.setViewportSize(viewport)
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort())
 await page.goto('/tests/studio-workspace/index.html?scenario=reference-offers')
 await page.getByTestId(mediaKind==='image'?'studio-mode-edit':'studio-mode-video').click()
 await page.getByTestId('studio-model-toggle').click();await expect(page.locator('.picker-choice')).toHaveCount(1);await page.locator('.picker-choice').click()
 await page.getByTestId('studio-prompt').fill('Isolated reference count quotation')
 for(const n of [1,2]){
  const before=await page.evaluate(()=>(window as any).studioFixture.calls.filter((c:any)=>c.path.endsWith('/quotes')).length)
  await page.getByTestId('studio-asset-input').setInputFiles({name:`reference-${n}.${mediaKind==='image'?'png':'mp4'}`,mimeType:mediaKind==='image'?'image/png':'video/mp4',buffer:mediaKind==='image'?Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9ZlS8AAAAASUVORK5CYII=','base64'):Buffer.from('synthetic video reference')})
  await expect(page.getByTestId('studio-asset-success')).toHaveCount(n)
  await expect(page.getByTestId('studio-quote')).toBeEnabled()
  expect(await page.evaluate(()=>(window as any).studioFixture.calls.filter((c:any)=>c.path.endsWith('/quotes')).length)).toBe(before)
  await page.getByTestId('studio-quote').click();await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText(`${(n*(mediaKind==='image'?1.25:3.25)).toFixed(2)} CNY`)
  const calls=await page.evaluate(()=>(window as any).studioFixture.calls)
  const quote=calls.filter((c:any)=>c.path.endsWith(`/${mediaKind}/quotes`)).at(-1)
  expect(quote.body.offer_id).toBe(`${mediaKind}-ref-${n}`)
  if(mediaKind==='image')expect(quote.body.spec).toMatchObject({images:n,resolution:'2K',aspect_ratio:'3:4',count:1})
  else {expect(quote.body).toMatchObject({duration:5,resolution:'720p',ratio:'16:9'});expect(quote.body.assets).toHaveLength(n);expect(quote.body.assets.every((asset:any)=>asset.kind==='video')).toBe(true)}
  expect(calls.filter((c:any)=>c.method==='POST'&&c.path.endsWith('/tasks'))).toHaveLength(0)
  if(n===1){await page.getByRole('button',{name:'返回修改'}).click();if(mediaKind==='image')await page.getByTestId('studio-mode-edit').click()}
 }
 await page.screenshot({path:info.outputPath(`reference-count-${mediaKind}-${viewport.width}.png`),animations:'disabled'})
})
