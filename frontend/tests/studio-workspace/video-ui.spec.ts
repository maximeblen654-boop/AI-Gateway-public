const videoFixture=fileURLToPath(new URL('./retention-video.mp4',import.meta.url))
async function open(page:Page,theme='light',invalidVideo=false) {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.addInitScript(({tasks,selected,compose})=>{
    sessionStorage.setItem('studio-media-view-9001',JSON.stringify({kind:'video',id:compose?undefined:selected,view:compose?'compose':undefined}))
    sessionStorage.setItem('studio-visual-fixture-video-ui',JSON.stringify({image:[],video:tasks}))
  },{tasks:[task(1,'completed',{billing_state:'billed',result_retention:{policy:'video_original_48h',persisted_at:'2026-10-23T04:00:00Z',expires_at:'2099-10-25T04:00:00Z',expired:false}}),task(2,'released'),task(3,'unknown')],selected:id(1),compose:invalidVideo})
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort())
  await page.route('**/studio-v2/api/video/operations/*/original',route=>invalidVideo?route.fulfill({body:'unreadable',contentType:'video/mp4'}):route.fulfill({path:videoFixture,contentType:'video/mp4'}))
  await page.goto(`/tests/studio-workspace/index.html?scenario=video-ui&theme=${theme}`)
  await expect(page.locator('.studio-gallery .studio-work')).toHaveCount(3)
}
