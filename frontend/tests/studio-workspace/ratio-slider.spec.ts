import {test,expect} from '@playwright/test'
for(const viewport of [{width:1440,height:900},{width:1366,height:650},{width:390,height:844}])test(`published ratio slider ${viewport.width}x${viewport.height}`,async({page},info)=>{
 await page.setViewportSize(viewport)
 await page.goto('/tests/studio-workspace/index.html?scenario=ratio-slider')
 const slider=page.locator('#studio-ratio-slider')
 await expect(slider).toBeEnabled();await expect(page.getByTestId('studio-ratio-toggle')).toHaveCount(0)
 await slider.focus();await page.keyboard.press('ArrowRight');await expect(slider).toHaveAttribute('aria-valuetext','1:1');await expect(slider).toHaveValue('500')
 await page.keyboard.press('End');await expect(slider).toHaveAttribute('aria-valuetext','16:9')
 await slider.scrollIntoViewIfNeeded()
 const track=await slider.boundingBox();expect(track).not.toBeNull()
 await page.mouse.move(track!.x+track!.width-8,track!.y+track!.height/2);await page.mouse.down();await page.mouse.move(track!.x+8,track!.y+track!.height/2,{steps:10});await page.mouse.up()
 await expect(slider).toHaveAttribute('aria-valuetext','9:16')
 const calls=await page.evaluate(()=>(window as any).studioFixture.calls as {method:string;path:string;body:any}[])
 expect(calls.filter(call=>call.method==='POST'&&(call.path.endsWith('/quotes')||call.path.endsWith('/tasks')))).toHaveLength(0)
 if(viewport.width<700)await slider.scrollIntoViewIfNeeded()
 await page.screenshot({path:info.outputPath(`ratio-slider-${viewport.width}.png`)})
 await page.getByTestId('studio-prompt').fill('Isolated ratio quote')
 await page.getByTestId('studio-quote').click()
 await expect(page.getByRole('dialog')).toBeVisible()
 const quoted=await page.evaluate(()=>(window as any).studioFixture.calls.find((call:any)=>call.path.endsWith('/image/quotes')))
 expect(quoted.body.offer_id).toBe('ratio-0');expect(quoted.body.spec.aspect_ratio).toBe('9:16')
})
test('mobile native ratio range supports touch dragging without quoting',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true})
 const page=await context.newPage();await page.goto('http://127.0.0.1:4295/tests/studio-workspace/index.html?scenario=ratio-slider')
 const slider=page.locator('#studio-ratio-slider');await expect(slider).toBeEnabled();await slider.scrollIntoViewIfNeeded()
 const track=(await slider.boundingBox())!;const client=await context.newCDPSession(page)
 const y=track.y+track.height/2,x=track.x+8,end=track.x+track.width-8
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
 for(let step=1;step<=10;step++)await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+(end-x)*step/10,y}]})
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 await expect(slider).toHaveAttribute('aria-valuetext','16:9')
 expect(await page.evaluate(()=>(window as any).studioFixture.calls.filter((call:any)=>call.method==='POST'&&(call.path.endsWith('/quotes')||call.path.endsWith('/tasks'))))).toEqual([])
 await context.close()
})
